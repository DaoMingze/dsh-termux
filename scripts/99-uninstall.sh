#!/data/data/com.termux/files/usr/bin/bash
# 99-uninstall.sh — remove a dsh-termux installation from this device.
#
# What an install creates, and therefore what this script removes:
#   1. the runtime dir (<runtime>, default ~/.local/opt/dsh-termux-runtime):
#      the glibc Node, the patched dsh tree, the bundled updater and patch set;
#   2. the `dsh` symlink in <bin dir> (default ~/.local/bin);
#   3. the node/npm/npx(/pnpm) shims next to it — only the ones this project
#      generated, never a node you installed yourself;
#   4. the PATH block tagged `# dsh-termux` in ~/.bashrc (a backup is kept);
#   5. the install record written into <repo>/config (node_installed_version /
#      node_bin). The config file itself stays: it is tracked project state.
#
# Never touched: Termux packages (glibc, glibc-repo, gnupg, patchelf), this
# repo checkout, and dsh's own data in ~/.dsh unless --purge is given.
#
# Usage:
#   bash scripts/99-uninstall.sh              # show the plan, ask, remove
#   bash scripts/99-uninstall.sh -y           # no prompts
#   bash scripts/99-uninstall.sh --dry-run    # show the plan, remove nothing
#   bash scripts/99-uninstall.sh --purge -y   # also delete ~/.dsh (config + sessions)
#
# Flags:
#   -y, --yes    do not ask (unsafe paths are still refused)
#   --dry-run    print the plan and exit without touching anything
#   --purge      also remove ~/.dsh; asks separately unless -y
#
# Env:
#   DSH_RUNTIME_DIR  runtime to remove (default ~/.local/opt/dsh-termux-runtime)
#   DSH_BIN_DIR      dir holding the dsh symlink + shims (default ~/.local/bin)
#   DSH_HOME         dsh's data dir, only used by --purge (default ~/.dsh)
set -euo pipefail

BASE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
source "$BASE_DIR/scripts/common.sh"

ASSUME_YES="${DSH_ASSUME_YES:-0}"
PURGE=0
DRY_RUN=0
for a in "$@"; do
	case "${a,,}" in
	-y | --yes) ASSUME_YES=1 ;;
	--purge) PURGE=1 ;;
	--dry-run | --dryrun) DRY_RUN=1 ;;
	-h | --help)
		sed -n '2,31p' "$0" >&2
		exit 0
		;;
	*)
		echo "99-uninstall.sh: unknown option: $a" >&2
		echo "Usage: bash scripts/99-uninstall.sh [-y] [--purge] [--dry-run]" >&2
		exit 2
		;;
	esac
done

RUNTIME_DIR="${DSH_RUNTIME_DIR:-$HOME/.local/opt/dsh-termux-runtime}"
BIN_DIR="${DSH_BIN_DIR:-$HOME/.local/bin}"
DSH_HOME="${DSH_HOME:-$HOME/.dsh}"
BASHRC="$HOME/.bashrc"

echo "==> [99] dsh-termux uninstall"
echo "    runtime : $RUNTIME_DIR"
echo "    bin dir : $BIN_DIR"
echo "    bashrc  : $BASHRC"
if [ "$PURGE" -eq 1 ]; then
	echo "    purge   : $DSH_HOME (dsh's own data)"
fi

# --- guards ----------------------------------------------------------------
# The paths come from environment variables, so prove the runtime is ours
# before deleting a directory: a mistyped DSH_RUNTIME_DIR must end in a refusal,
# not in "rm -rf" of something a user actually wanted to keep.
runtime_is_ours() {
	local dir="$1" marker
	[ -n "$dir" ] && [ -d "$dir" ] || return 1
	case "$dir" in
	/ | /data | /data/data | /data/data/com.termux | /data/data/com.termux/files | \
		/data/data/com.termux/files/home | "$HOME" | "$HOME/.local" | "$HOME/.local/opt" | \
		"$HOME/.config" | "$HOME/.dsh")
		return 1
		;;
	esac
	for marker in node/bin/node work/node_modules/@deepseek-ai/dsh work/dsh \
		scripts/update-dsh.sh; do
		[ -e "$dir/$marker" ] && return 0
	done
	return 1
}

is_our_shim() { [ -f "$1" ] && grep -qF "$DSH_NODE_SHIM_TAG" "$1" 2>/dev/null; }

dsh_symlink_points_in() {
	[ -L "$BIN_DIR/dsh" ] &&
		case "$(readlink "$BIN_DIR/dsh")" in
		"$RUNTIME_DIR"/*) return 0 ;;
		*) return 1 ;;
		esac
}

config_has_record() {
	local cfg out=1
	cfg="$(dsh_config_file)"
	[ -f "$cfg" ] || return 1
	[ -n "$(dsh_config_get node_installed_version)" ] && out=0
	[ -n "$(dsh_config_get node_bin)" ] && out=0
	return "$out"
}

# --- the plan --------------------------------------------------------------
removals=()
notes=()

if [ -d "$RUNTIME_DIR" ]; then
	if runtime_is_ours "$RUNTIME_DIR"; then
		removals+=("runtime dir: $RUNTIME_DIR")
	else
		notes+=("!! $RUNTIME_DIR exists but does not look like a dsh-termux runtime — left alone")
	fi
fi

if dsh_symlink_points_in; then
	removals+=("dsh symlink: $BIN_DIR/dsh -> $(readlink "$BIN_DIR/dsh")")
elif [ -e "$BIN_DIR/dsh" ] || [ -L "$BIN_DIR/dsh" ]; then
	if grep -qF 'dsh wrapper generated by dsh-termux' "$BIN_DIR/dsh" 2>/dev/null; then
		removals+=("dsh wrapper: $BIN_DIR/dsh")
	else
		notes+=("!! $BIN_DIR/dsh is not ours — left alone")
	fi
fi

for s in node npm npx pnpm; do
	is_our_shim "$BIN_DIR/$s" && removals+=("node shim: $BIN_DIR/$s")
done
for s in node npm npx pnpm; do
	if { [ -e "$BIN_DIR/$s" ] || [ -L "$BIN_DIR/$s" ]; } && ! is_our_shim "$BIN_DIR/$s"; then
		notes+=("!! $BIN_DIR/$s is not a dsh-termux shim — left alone")
	fi
done

if grep -qF '# dsh-termux' "$BASHRC" 2>/dev/null; then
	removals+=("PATH block tagged '# dsh-termux' in $BASHRC (backup kept next to it)")
fi

if config_has_record; then
	removals+=("install record in $(dsh_config_file) (node_installed_version, node_bin)")
fi

if [ "$PURGE" -eq 1 ] && [ -d "$DSH_HOME" ]; then
	removals+=("dsh data: $DSH_HOME (config + sessions)")
fi

if [ ${#removals[@]} -eq 0 ]; then
	echo
	echo "Nothing to remove: no dsh-termux runtime, symlink, shim or PATH line found."
	for n in "${notes[@]}"; do echo "  $n"; done
	exit 0
fi

echo
echo "==> Will remove:"
for r in "${removals[@]}"; do echo "  - $r"; done
for n in "${notes[@]}"; do echo "  $n"; done

if [ "$DRY_RUN" -eq 1 ]; then
	echo
	echo "Dry run: nothing was removed."
	exit 0
fi

if [ "$ASSUME_YES" -eq 1 ]; then
	echo
	echo "==> Removing (assuming yes)"
elif ! ask_yes_no "Remove the items above?" no; then
	echo "Aborted. Nothing was removed."
	exit 0
fi

# --- removal ---------------------------------------------------------------
# A live dsh keeps its files open; on Android that turns removal into a pile of
# partial failures. Warn, do not block: the check is best-effort (pgrep is not
# guaranteed on a minimal Termux).
if command -v pgrep >/dev/null 2>&1 && pgrep -f "dsh-termux-runtime" >/dev/null 2>&1; then
	echo "!! a process from this runtime looks alive; stop it if removal fails." >&2
fi

drop_bashrc_block() {
	local tmp line dropping=0
	[ -f "$BASHRC" ] || return 0
	grep -qF '# dsh-termux' "$BASHRC" || return 0
	tmp="$BASHRC.99.$$"
	cp "$BASHRC" "$BASHRC.dsh-uninstall.bak"
	: >"$tmp"
	# The block this project appends is: the tag line, two comment lines, then
	# one `export PATH="<bin dir>:$PATH"`. Drop exactly that shape — the PATH
	# line is recognised by position, not by its value, so a bin dir that moved
	# since the install still gets removed. A tag line followed by anything else
	# (older or hand-edited) loses only the tag and our two comment lines; every
	# other line in your ~/.bashrc is copied through untouched.
	while IFS= read -r line || [ -n "$line" ]; do
		if [ "$line" = "# dsh-termux" ]; then
			dropping=1
			continue
		fi
		if [ "$dropping" -eq 1 ]; then
			case "$line" in
			"# Prepend dsh-termux bin dir"* | "# node/npm shims resolve here.") continue ;;
			export[[:space:]]PATH=*)
				dropping=0
				continue
				;;
			*) dropping=0 ;;
			esac
		fi
		printf '%s\n' "$line" >>"$tmp"
	done <"$BASHRC"
	mv "$tmp" "$BASHRC"
	echo "    removed the PATH block from $BASHRC (backup: $BASHRC.dsh-uninstall.bak)"
}

if dsh_symlink_points_in || grep -qF 'dsh wrapper generated by dsh-termux' "$BIN_DIR/dsh" 2>/dev/null; then
	rm -f "$BIN_DIR/dsh"
	echo "    removed $BIN_DIR/dsh"
fi

for s in node npm npx pnpm; do
	if is_our_shim "$BIN_DIR/$s"; then
		rm -f "$BIN_DIR/$s"
		echo "    removed shim $BIN_DIR/$s"
	fi
done

drop_bashrc_block

if config_has_record; then
	dsh_config_set node_installed_version "" &&
		dsh_config_set node_bin "" &&
		echo "    cleared the install record in $(dsh_config_file)"
fi

if runtime_is_ours "$RUNTIME_DIR"; then
	rm -rf "${RUNTIME_DIR:?}"
	echo "    removed runtime $RUNTIME_DIR"
fi

if [ "$PURGE" -eq 1 ] && [ -d "$DSH_HOME" ]; then
	rm -rf "${DSH_HOME:?}"
	echo "    removed dsh data $DSH_HOME"
fi

echo
echo "==> [99] Done."
echo "    Left in place on purpose:"
echo "      Termux packages (glibc, glibc-repo, gnupg, patchelf) — remove with"
echo "      'pkg uninstall ...' if nothing else needs them;"
echo "      this repo checkout, and $(dsh_config_file) (only its install record was cleared)."
if [ "$PURGE" -eq 0 ]; then
	echo "      dsh's own data in $DSH_HOME — pass --purge to delete it too."
fi
echo "    Open a new shell (or 'exec bash') so the removed PATH line stops applying."
